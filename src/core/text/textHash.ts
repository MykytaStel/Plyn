/**
 * A fast, synchronous fingerprint of a text (cyrb53 plus the length), used to
 * find a duplicate without comparing every stored book (0.25, IMP-06).
 *
 * Not cryptographic: a match is always confirmed by comparing the texts. It is
 * synchronous on purpose, so it can run inside an IndexedDB upgrade
 * transaction, where awaiting `crypto.subtle` would commit the transaction.
 */
export function textHash(text: string): string {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507);
  h1 ^= Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507);
  h2 ^= Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  const hash = 4294967296 * (2097151 & h2) + (h1 >>> 0);
  return `${hash.toString(36)}:${text.length.toString(36)}`;
}
